export const ar: Record<string, string> = { ...arBase, ...arExtra }

interface I18nValue {
  lang: Lang
  dir: 'ltr' | 'rtl'
  setLang: (lang: Lang) => void
  t: (en: string, arText?: string) => string
  tx: (en: string, arText: string) => string
  formatDate: (value: string | Date, pattern?: string) => string
  fromNow: (value: string | Date) => string
  isRTL: boolean
}

const I18nContext = createContext<I18nValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const language = useAppStore((s) => s.language)
  const theme = useAppStore((s) => s.theme)
  const setLanguage = useAppStore((s) => s.setLanguage)

  useEffect(() => {
    const root = document.documentElement
    root.lang = language
    root.dir = language === 'ar' ? 'rtl' : 'ltr'
  }, [language])

  useEffect(() => {
    document.documentElement.classList.toggle('dark', theme === 'dark')
  }, [theme])

  const value = useMemo<I18nValue>(() => {
    const isRTL = language === 'ar'
    return {
      lang: language,
      dir: isRTL ? 'rtl' : 'ltr',
      isRTL,
      setLang: setLanguage,
      t: (en: string, arText?: string) => (isRTL ? arText ?? ar[en] ?? en : en),
      tx: (en: string, arText: string) => (isRTL ? arText : en),
      formatDate: (value: string | Date, pattern?: string) => formatDate(value, language, pattern),
      fromNow: (value: string | Date) => fromNow(value, language),
    }
  }, [language, setLanguage])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider')
  return ctx
}
